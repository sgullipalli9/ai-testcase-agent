/**
 * Deterministic Playwright spec generator. Given the same suite JSON it always produces the same
 * file, so generated tests are reviewable in diffs and never contain hallucinated code.
 */
import type { SiteConfig } from '../config.js';
import type { TestSuite, ValidatedTestCase } from '../model/testCase.js';
import { emitStep, narrateStep } from '../steps/actions.js';
import { q } from '../steps/target.js';

const indent = (code: string, n: number) =>
  code
    .split('\n')
    .map((l) => (l ? ' '.repeat(n) + l : l))
    .join('\n');

const SORT_HELPER = `
function isSorted(values: string[], order: 'asc' | 'desc', by: 'text' | 'number'): boolean {
  const num = (s: string) => Number(s.replace(/[^0-9.-]/g, ''));
  const cmp = (a: string, b: string) => (by === 'number' ? num(a) - num(b) : a.localeCompare(b));
  return values.every((v, i) => i === 0 || (order === 'asc' ? cmp(values[i - 1]!, v) <= 0 : cmp(values[i - 1]!, v) >= 0));
}
`;

function emitTest(tc: ValidatedTestCase): string {
  const tags = [`@${tc.priority}`, `@${tc.type}`, ...tc.tags.map((t) => `@${t.replace(/\s+/g, '-')}`)];
  const annotations = [`{ type: 'objective', description: ${q(tc.objective)} }`];
  if (tc.validation.status === 'suspected-defect' || tc.validation.status === 'quarantined') {
    annotations.push(`{ type: ${q(tc.validation.status)}, description: ${q(tc.validation.rationale ?? tc.validation.lastError ?? '')} }`);
  }
  const details = `{\n  tag: [${[...new Set(tags)].map(q).join(', ')}],\n  annotation: [\n${annotations.map((a) => `    ${a},`).join('\n')}\n  ],\n}`;
  const body: string[] = [];
  if (tc.validation.status === 'suspected-defect') {
    body.push(`// Suspected product defect — kept as an expected failure. Remove test.fail() once fixed.`, `test.fail();`);
  }
  tc.steps.forEach((s, i) => {
    body.push(`// ${i + 1}. ${narrateStep(s)}`);
    body.push(emitStep(s));
  });
  const fn = tc.validation.status === 'quarantined' ? 'test.fixme' : 'test';
  return `${fn}(${q(`${tc.id} ${tc.title}`)}, ${details}, async ({ page }) => {\n${indent(body.join('\n'), 2)}\n});`;
}

export function generateSpec(site: SiteConfig, suite: TestSuite, requiresAuth: boolean): string {
  const usesSort = suite.testCases.some((tc) => tc.steps.some((s) => s.action === 'expectSorted'));
  const beforeEach =
    requiresAuth && site.auth
      ? `\n  test.beforeEach(async ({ page }) => {\n    // ${site.auth.description}\n${indent(site.auth.steps.map(emitStep).join('\n'), 4)}\n  });\n`
      : '';
  const tests = suite.testCases.map((tc) => indent(emitTest(tc), 2)).join('\n\n');
  return `// AUTO-GENERATED by ai-testcase-agent — do not edit by hand.
// Source of truth: ./test-cases.json (edit it, then run \`npm run render\`).
// Site: ${site.name} · Module: ${suite.module} · Generator: ${suite.generator.model}
import { test, expect } from '@playwright/test';
${usesSort ? SORT_HELPER : ''}
test.describe(${q(`${site.name} › ${suite.module}`)}, () => {${beforeEach}
${tests}
});
`;
}
